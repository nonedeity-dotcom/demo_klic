/**
 * The app's built-in reference: everything it nudges you towards, written out
 * with the reasoning behind it.
 *
 * Bundled as data rather than fetched — there is no server anywhere in this
 * app, and a tip that needs a network round trip is a tip you can't read on a
 * phone that's deliberately in another room.
 *
 * Source material: four talks the app itself was built from — a focus system
 * (50/10, boredom before work, entry ritual), a dopamine/trigger detox, a
 * "why people quit halfway" model (honeymoon → the dip → plateau), and one on
 * analysis paralysis. Where a source states something as fact that is really
 * its author's claim or a popular simplification, the tip carries a `caveat`
 * instead of repeating it as settled — the practice usually stands on its own
 * without the shaky explanation underneath it.
 */

export interface LibrarySection {
  id: string;
  title: string;
  blurb: string;
}

export interface Tip {
  id: string;
  section: LibrarySection["id"];
  /** One line — what shows collapsed, and what a tip-of-the-day says. */
  short: string;
  /** The paragraph behind it, revealed on tap. */
  full: string;
  /** Honest note where the source is shakier than it sounds. */
  caveat?: string;
  /**
   * Whether this takes part in the rotation shown on the report screen.
   * Explanations of a model ("what the dip is") are worth reading once and
   * make a poor nudge, so they stay reference-only.
   */
  rotate: boolean;
}

